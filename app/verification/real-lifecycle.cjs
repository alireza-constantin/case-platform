// Run after closing/reopening the real browser profile and restarting Go.
async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const absolute = path => new URL(path, page.url()).href;
  const get = async path => { const response = await page.request.get(absolute(path)); assert(response.ok(), 'Owned API read failed'); return response.json(); };
  const ids = await page.evaluate(() => JSON.parse(localStorage.getItem('verification-run-ids')));
  assert(ids?.phoneId && ids?.terminalId, 'Same-profile verification identities must survive the full browser restart');
  const catalogue = (await get('/api/cases')).cases;
  const phoneTitle = catalogue.find(item => item.case_id === 'phone-demo').title;
  const terminalTitle = catalogue.find(item => item.case_id === 'terminal-demo').title;
  const beforePhone = await get(`/api/playthroughs/${ids.phoneId}`);
  const beforeTerminal = await get(`/api/playthroughs/${ids.terminalId}`);
  assert(beforePhone.playthrough.revision === ids.phoneRevision && beforePhone.playthrough.completed_at === ids.phoneCompletedAt && beforePhone.view.gallery_unlocked, 'Phone committed state survives Go and browser restart');
  assert(beforeTerminal.playthrough.revision === ids.terminalRevision && beforeTerminal.playthrough.completed_at === ids.terminalCompletedAt && beforeTerminal.view.workstation_ready, 'Terminal committed state survives Go and browser restart');
  const errors = []; const capture = message => { if (message.type() === 'error' && message.text().includes('React')) errors.push(message.text()); };
  page.on('console', capture);
  await page.getByRole('button', { name: `Continue ${phoneTitle}`, exact: true }).click();
  await page.getByRole('heading', { name: 'Case complete', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Messages', exact: true }).click();
  assert(await page.locator('.phone-messages li').count() === beforePhone.view.messages.length, 'Phone resume displays its committed clues');
  await page.getByRole('button', { name: 'Back to cases', exact: true }).click();
  await page.getByRole('button', { name: `Continue ${terminalTitle}`, exact: true }).click();
  await page.getByRole('heading', { name: 'Case complete', exact: true }).waitFor();
  let release; const held = new Promise(resolve => { release = resolve; });
  let canceled; const cancellation = new Promise(resolve => { canceled = resolve; });
  const assetPath = `/api/playthroughs/${ids.terminalId}/assets/${ids.terminalAsset}`;
  const failure = request => { if (new URL(request.url()).pathname === assetPath) canceled(); };
  page.on('requestfailed', failure);
  await page.route(`**${assetPath}`, async route => {
    const realResponse = await route.fetch(); assert(realResponse.ok(), 'Actual Go asset authorization must succeed before holding delivery');
    await held; await route.fulfill({ response: realResponse }).catch(() => {});
  });
  const requested = page.waitForRequest(`**${assetPath}`);
  await page.getByRole('button', { name: `Read ${beforeTerminal.view.protected_file.name}`, exact: true }).click();
  await requested;
  await page.getByRole('button', { name: 'Back to cases', exact: true }).click();
  await page.getByRole('button', { name: `Continue ${phoneTitle}`, exact: true }).click();
  await Promise.race([cancellation, new Promise((_, reject) => setTimeout(() => reject(new Error('Case exit must cancel the in-flight protected fetch')), 3000))]);
  release(); await page.unroute(`**${assetPath}`); page.off('requestfailed', failure);
  await page.getByRole('button', { name: 'Messages', exact: true }).waitFor();
  assert(await page.getByRole('log', { name: 'Command output' }).count() === 0 && await page.getByRole('region', { name: 'Protected file' }).count() === 0, 'No Terminal effects/reader leak into Phone');
  await page.getByRole('heading', { name: 'Case complete', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Back to cases', exact: true }).click();
  await page.getByRole('button', { name: `Restart ${phoneTitle}`, exact: true }).click();
  await page.getByRole('button', { name: 'Gallery', exact: true }).click();
  const freshPhoneId = new URL(page.url()).pathname.split('/')[2];
  assert(freshPhoneId !== ids.phoneId && await page.getByText('The gallery is locked', { exact: true }).isVisible(), 'Phone Restart creates a new locked identity');
  const newPhone = await get(`/api/playthroughs/${freshPhoneId}`);
  assert(newPhone.playthrough.revision === 0 && newPhone.playthrough.completed_at === null, 'Phone Restart has server-initialized state');
  await page.getByRole('button', { name: 'Back to cases', exact: true }).click();
  await page.getByRole('button', { name: `Restart ${terminalTitle}`, exact: true }).click();
  await page.getByText('Workstation requires attention', { exact: true }).waitFor();
  const freshTerminalId = new URL(page.url()).pathname.split('/')[2];
  const newTerminal = await get(`/api/playthroughs/${freshTerminalId}`);
  assert(freshTerminalId !== ids.terminalId && newTerminal.playthrough.revision === 0 && newTerminal.playthrough.completed_at === null && !newTerminal.view.protected_file, 'Terminal Restart creates a fresh locked identity');
  const oldPhone = await get(`/api/playthroughs/${ids.phoneId}`);
  const oldTerminal = await get(`/api/playthroughs/${ids.terminalId}`);
  assert(oldPhone.playthrough.completed_at === ids.phoneCompletedAt && oldTerminal.playthrough.completed_at === ids.terminalCompletedAt && oldPhone.playthrough.revision === ids.phoneRevision && oldTerminal.playthrough.revision === ids.terminalRevision, 'Restart preserves old committed runs and first completion');
  const runs = (await get('/api/playthroughs')).playthroughs;
  assert([ids.phoneId, ids.terminalId, freshPhoneId, freshTerminalId].every(id => runs.some(run => run.playthrough_id === id)), 'Own list retains old and new runs');
  assert(errors.length === 0, 'No React cleanup errors'); page.off('console', capture);
  const evidence = { ...ids, freshPhoneId, freshTerminalId };
  await page.evaluate(evidence => localStorage.setItem('verification-run-ids', JSON.stringify(evidence)), evidence);
  return { restoredCompletedRuns: 2, retainedRunCount: runs.length, freshPhoneId, freshTerminalId, inFlightAssetCanceled: true };
}
