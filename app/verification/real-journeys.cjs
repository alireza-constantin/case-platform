// Real browser -> same-origin Go -> PostgreSQL. No synthetic HTTP responses.
async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const absolute = path => new URL(path, page.url()).href;
  const get = async path => { const response = await page.request.get(absolute(path)); assert(response.ok(), 'Owned API read failed'); return response.json(); };
  await page.goto(new URL(page.url()).origin);
  const catalogue = await get('/api/cases');
  const phoneTitle = catalogue.cases.find(item => item.case_id === 'phone-demo').title;
  const terminalTitle = catalogue.cases.find(item => item.case_id === 'terminal-demo').title;
  await page.evaluate(() => { const input = document.createElement('input'); input.type = 'file'; input.id = 'verification-private-input'; input.hidden = true; document.body.append(input); });
  await page.locator('#verification-private-input').setInputFiles('output/ticket7-private-inputs.json');
  const privateInputs = JSON.parse(await page.locator('#verification-private-input').evaluate(input => input.files[0].text()));
  await page.locator('#verification-private-input').evaluate(input => input.remove());
  await page.getByRole('button', { name: `Start ${phoneTitle}`, exact: true }).click();
  await page.getByRole('button', { name: 'Messages', exact: true }).click();
  const phoneId = new URL(page.url()).pathname.split('/')[2];
  const initialPhone = await get(`/api/playthroughs/${phoneId}`);
  assert(!initialPhone.view.gallery_unlocked && !initialPhone.view.gallery_assets && !JSON.stringify(initialPhone).includes(privateInputs.phonePassword), 'Initial Phone projection withholds answer and protected inventory');
  assert(initialPhone.view.messages.every(message => message.text.length > 0) && await page.locator('.phone-messages li').count() === initialPhone.view.messages.length, 'Phone displays server-projected public clues');
  await page.getByRole('button', { name: 'Phone home' }).click();
  await page.getByRole('button', { name: 'Gallery', exact: true }).click();
  await page.getByLabel('Gallery password').fill('verification-deliberately-wrong');
  await page.getByRole('button', { name: 'Unlock gallery', exact: true }).click();
  await page.getByText('That password did not unlock the gallery.', { exact: true }).waitFor();
  const wrong = await get(`/api/playthroughs/${phoneId}`);
  assert(!wrong.view.gallery_unlocked && wrong.playthrough.revision === 1, 'Persisted wrong attempt remains locked and advances once');
  await page.getByLabel('Gallery password').fill(privateInputs.phonePassword);
  await page.getByRole('button', { name: 'Unlock gallery', exact: true }).click();
  await page.getByRole('button', { name: 'Open gallery', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Gallery', exact: true }).click();
  await page.getByRole('button', { name: 'Open gallery', exact: true }).click();
  await page.getByRole('heading', { name: 'Case complete', exact: true }).waitFor();
  await page.locator('.phone-gallery img').waitFor();
  const phone = await get(`/api/playthroughs/${phoneId}`);
  assert(phone.playthrough.revision === 3 && phone.playthrough.completed_at, 'Phone unlock/open/first completion commit at expected revisions');
  const phoneAsset = phone.view.gallery_assets[0].asset_id;
  const image = await page.request.get(absolute(`/api/playthroughs/${phoneId}/assets/${phoneAsset}`));
  assert(image.ok() && image.headers()['cache-control'] === 'no-store' && image.headers()['content-type'].startsWith('image/svg+xml'), 'Owner receives protected no-store image');
  await page.screenshot({ path: 'output/playwright/ticket7real/phone-completed.png', fullPage: true });
  await page.getByRole('button', { name: 'Back to cases', exact: true }).click();
  await page.getByRole('button', { name: `Start ${terminalTitle}`, exact: true }).click();
  await page.getByLabel('Command', { exact: true }).waitFor();
  const terminalId = new URL(page.url()).pathname.split('/')[2];
  const initialTerminal = await get(`/api/playthroughs/${terminalId}`);
  assert(!initialTerminal.view.workstation_ready && !initialTerminal.view.protected_file, 'Initial Terminal projection withholds protected file');
  const send = async command => {
    const responsePromise = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/actions') && response.request().method() === 'POST');
    await page.getByLabel('Command', { exact: true }).fill(command);
    await page.getByLabel('Command', { exact: true }).press('Enter');
    const response = await responsePromise; assert(response.ok(), 'Simulated command failed at transport');
    const result = await response.json();
    await page.getByLabel('Command', { exact: true }).waitFor({ state: 'visible' });
    assert(result.outcome.lines.every(line => typeof line === 'string'), 'Command lines retain case-owned shape');
    return result;
  };
  const help = await send('help');
  const notes = await send('cat readme.txt');
  assert(help.playthrough.revision === 0 && notes.playthrough.revision === 0, 'Read-only help/notes are non-advancing');
  const denied = await send('cat report.txt');
  assert(denied.outcome.ok === false && denied.playthrough.revision === 0, 'Premature protected read is denied without mutation');
  const maintenance = initialTerminal.view.entries.find(entry => entry.kind === 'directory');
  const selected = await send(`cd ${maintenance.name}`); assert(selected.outcome.ok, 'Public projected maintenance directory is navigable');
  const plan = selected.view.entries.find(entry => entry.kind === 'file');
  const instructions = await send(`cat ${plan.name}`);
  assert(privateInputs.terminalCommands.every(command => instructions.outcome.lines.join('\n').includes(command)), 'Actual sequence is discoverable in server-produced notes');
  let ready;
  for (const command of privateInputs.terminalCommands) { ready = await send(command); assert(ready.outcome.ok, 'Discovered prerequisite command must succeed'); }
  assert(ready.view.workstation_ready, 'Real prerequisites project ready state');
  await page.reload();
  await page.getByText('Workstation ready', { exact: true }).waitFor();
  const root = await send('cd /');
  const archive = root.view.entries.find(entry => entry.kind === 'directory' && entry.name !== maintenance.name);
  const opened = await send(`cd ${archive.name}`);
  assert(opened.outcome.ok && opened.view.protected_file, 'Permitted archive projects its file');
  await page.getByRole('button', { name: `Read ${opened.view.protected_file.name}`, exact: true }).click();
  await page.getByRole('heading', { name: 'Case complete', exact: true }).waitFor();
  await page.locator('.terminal-file pre').waitFor();
  const terminal = await get(`/api/playthroughs/${terminalId}`);
  assert(terminal.playthrough.revision === opened.playthrough.revision + 1 && terminal.playthrough.completed_at, 'Terminal read and first completion advance once');
  const terminalAsset = terminal.view.protected_file.asset_id;
  const file = await page.request.get(absolute(`/api/playthroughs/${terminalId}/assets/${terminalAsset}`));
  assert(file.ok() && file.headers()['cache-control'] === 'no-store' && file.headers()['content-type'].startsWith('text/plain'), 'Owner receives protected no-store text');
  assert(await page.locator('.terminal-file pre').textContent() === await file.text(), 'Reader displays actual authorized response bytes');
  await page.screenshot({ path: 'output/playwright/ticket7real/terminal-completed.png', fullPage: true });
  const evidence = { phoneId, terminalId, phoneAsset, terminalAsset, phoneRevision: phone.playthrough.revision, terminalRevision: terminal.playthrough.revision, phoneCompletedAt: phone.playthrough.completed_at, terminalCompletedAt: terminal.playthrough.completed_at };
  await page.evaluate(evidence => localStorage.setItem('verification-run-ids', JSON.stringify(evidence)), evidence);
  return evidence; // Safe identities/metadata only; no credentials or solution input.
}
